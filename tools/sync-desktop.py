#!/usr/bin/env python3
"""Generate native desktop catalogs/constants from shared/. Python stdlib only, no network."""
from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
HEADER = '// Generated by tools/sync-desktop.py from shared/. Edit the shared originals.\n'

def quoted(value):
    # Swift and C# string literal grammars agree for these JSON escapes. Reject surrogate data.
    value.encode('utf-8')
    return json.dumps(value, ensure_ascii=False).replace('\\/', '/')

def load_sources(root=ROOT):
    contract = json.loads((root/'shared/desktop.json').read_text(encoding='utf-8'))
    templates = json.loads((root/'shared/catalog/templates.json').read_text(encoding='utf-8'))
    cases = json.loads((root/'shared/fixtures/layout.json').read_text(encoding='utf-8'))
    policy=json.loads((root/'shared/collection.json').read_text(encoding='utf-8'))
    if policy.get('version')!=1 or any(len(policy[k])!=4 for k in ['names','colors','weights','duplicatePetals','exchangePetals','forms']) or len(policy['synthesisPercent'])!=3:
        raise ValueError('Invalid collection policy')
    if sum(policy['weights'])!=10000 or any(type(x) is not int or x<=0 for k in ['weights','duplicatePetals','exchangePetals'] for x in policy[k]): raise ValueError('Invalid collection rates')
    if any(not re.fullmatch(r'#[A-Fa-f0-9]{6}',v) for v in policy['colors']) or any(type(x) is not int or not 1<=x<=100 for x in policy['synthesisPercent']): raise ValueError('Invalid synthesis policy')
    forms=[f for group in policy['forms'] for f in group]
    if len(forms)!=50 or len(set(forms))!=50 or any(not re.fullmatch(r'[a-z]+',f) for f in forms): raise ValueError('Duplicate/missing collection form')
    if not 0<=policy['failureRefund']<policy['synthesisCost'] or policy['craftCost']<1: raise ValueError('Invalid material cost')
    goals=[m['owned'] for m in policy['milestones']]
    if goals!=sorted(set(goals)) or any(not 1<=m['owned']<=300 or not 0<=m['grade']<4 or m['amount']<1 for m in policy['milestones']): raise ValueError('Invalid collection milestones')
    if contract.get('format') != 'myday-desktop-contract' or contract.get('version') != 1:
        raise ValueError('Unsupported shared contract')
    for group in ['limits', 'chat', 'growth']:
        for key, number in contract[group].items():
            if not re.fullmatch(r'[A-Z][A-Za-z0-9]*', key) or type(number) is not int or not 1 <= number <= 10_000_000:
                raise ValueError('Invalid numeric rule: '+key)
    for group in ['categories', 'layouts', 'references']:
        ids = [value['id'] for value in contract[group]]
        if len(ids) != len(set(ids)) or not ids:
            raise ValueError('Duplicate/empty metadata group: '+group)
    limits = contract['limits']
    growth=contract['growth']
    if growth['GrowthMaxLevel'] != 100 or growth['GrowthMaxXP'] != 3590:
        raise ValueError('Growth curve and cap require coordinated native changes')
    if len(contract['growthProfiles']) != 3: raise ValueError('Expected three growth pace profiles')
    for profile in contract['growthProfiles']:
        if len(profile['week']) != 7 or any(type(f) is not int or not 0 <= f <= 63 for f in profile['week']) or not 1 <= profile['expectedDays'] <= 1000:
            raise ValueError('Invalid growth pace profile')
    for lower, upper in [('MinWidth','MaxWidth'),('MinHeight','MaxHeight')]:
        if limits[lower] > limits[upper]: raise ValueError('Inverted geometry bounds')
    for value in contract['design'].values():
        for color in value if isinstance(value,list) else [value]:
            if not re.fullmatch(r'#[A-Fa-f0-9]{6}', color): raise ValueError('Invalid color')
    if len(contract['design']['Backgrounds']) != 3: raise ValueError('Saved themes require three stable slots')
    seen = set()
    for template in templates:
        if not re.fullmatch(r'[a-z0-9-]+', template['id']) or template['id'] in seen:
            raise ValueError('Invalid/duplicate template ID')
        seen.add(template['id'])
        for key, group in [('category','categories'),('layout','layouts'),('reference','references')]:
            if template[key] not in [entry['id'] for entry in contract[group]]: raise ValueError('Unknown '+key)
        if template['style'] not in contract['pageStyles'] or type(template['minutes']) is not int or not 1 <= template['minutes'] <= 120:
            raise ValueError('Invalid template metadata')
        if not 1 <= len(template['sections']) <= limits['MaxBlocks']: raise ValueError('Invalid sections')
        for section in template['sections']:
            if section['kind'] not in contract['blockKinds'] or section['kind'] in ['photo','photo-slot']:
                raise ValueError('Unknown text template section')
            for key, maximum in [('title','MaxTitleUtf16'),('prompt','MaxPromptUtf16')]:
                if len(section[key].encode('utf-16-le'))//2 > limits[maximum]: raise ValueError('Section '+key+' too long')
    if not templates or len(templates) > 500: raise ValueError('Invalid template count')
    if len(cases) < 1: raise ValueError('No shared behavior fixtures')
    for case in cases:
        if type(case['resize']) is not bool or [len(case[k]) for k in ['original','delta','expected']] != [4,2,4]:
            raise ValueError('Invalid layout fixture')
        if any(type(n) is not int for k in ['original','delta','expected'] for n in case[k]): raise ValueError('Invalid fixture coordinate')
    digest = hashlib.sha256(json.dumps([contract,templates,cases,policy],ensure_ascii=False,sort_keys=True,separators=(',',':')).encode()).hexdigest()
    return contract, templates, cases, digest

def render(root=ROOT):
    c, templates, cases, digest = load_sources(root)
    policy=json.loads((root/'shared/collection.json').read_text(encoding='utf-8'))
    collection_cs=[HEADER,'namespace MyDay.Windows.Core {\n    public static class CollectionPolicy {\n']
    collection_kt=[HEADER,'package com.myday.diary.diary\n\ninternal object SharedCollection {\n']
    for key in ['names','colors','weights','duplicatePetals','exchangePetals','synthesisPercent']:
        vals=policy[key];strings=isinstance(vals[0],str);args=','.join(quoted(x) if strings else str(x) for x in vals)
        collection_cs.append('        public static readonly '+('string' if strings else 'int')+'[] '+key[0].upper()+key[1:]+'={'+args+'};\n')
        collection_kt.append('    val '+key+'='+('arrayOf' if strings else 'intArrayOf')+'('+args+')\n')
    for key in ['synthesisCost','failureRefund','craftCost']:
        collection_cs.append('        public const int '+key[0].upper()+key[1:]+'='+str(policy[key])+';\n')
        collection_kt.append('    const val '+key+'='+str(policy[key])+'\n')
    collection_cs.append('        public static readonly string[][] Forms={'+','.join('new[]{'+','.join(map(quoted,group))+'}' for group in policy['forms'])+'};\n')
    collection_kt.append('    val forms=arrayOf('+','.join('arrayOf('+','.join(map(quoted,group))+')' for group in policy['forms'])+')\n')
    rows=[[m[k] for k in ['owned','grade','amount']] for m in policy['milestones']]
    collection_cs.append('        public static readonly int[][] Milestones={'+','.join('new[]{'+','.join(map(str,row))+'}' for row in rows)+'};\n    }\n}\n')
    collection_kt.append('    val milestones=arrayOf('+','.join('intArrayOf('+','.join(map(str,row))+')' for row in rows)+')\n}\n')
    numbers = dict(c['limits'], **c['chat'], **c['growth'], TemplateCount=len(templates))
    arrays = {'BlockKinds':c['blockKinds'], 'PageStyles':c['pageStyles']}
    for prefix, group, value in [('Categories','categories','id'),('CategoryNames','categories','name'),
            ('LayoutIds','layouts','id'),('LayoutNames','layouts','name'),('ReferenceIds','references','id'),('ReferenceUrls','references','url')]:
        arrays[prefix] = [entry[value] for entry in c[group]]
    colors = {key:value for key,value in c['design'].items() if isinstance(value,str)}
    arrays['Backgrounds'] = c['design']['Backgrounds']
    cs = [HEADER, 'namespace MyDay.Windows.Core {\n    public static class DesktopContract {\n',
          '        public const string SourceDigest='+quoted(digest)+';\n']
    cs += ['        public const int '+key+'='+str(value)+';\n' for key,value in numbers.items()]
    cs += ['        public const string '+key+'='+quoted(value)+';\n' for key,value in colors.items()]
    cs += ['        public static readonly string[] '+key+'={'+','.join(map(quoted,values))+'};\n' for key,values in arrays.items()]
    cs += ['    }\n    public static class DesktopFixtures {\n        public static readonly int[][] Layouts={\n']
    cs += ['            new[]{'+','.join(map(str,[int(case['resize']),*case['original'],*case['delta'],*case['expected']]))+'},\n' for case in cases]
    cs += ['        };\n        public static readonly int[][] GrowthProfiles={\n']
    cs += ['            new[]{'+','.join(map(str,[p['expectedDays'],*p['week']]))+'},\n' for p in c['growthProfiles']]
    cs += ['        };\n    }\n}\n']
    native_templates = [HEADER, 'namespace MyDay.Windows.Core {\n    internal static class SharedTemplateCatalog {\n        internal static readonly JournalTemplate[] All={\n']
    for t in templates:
        args = [quoted(t[key]) for key in ['id','name','description','style','category']]+[str(t['minutes'])]+[quoted(t[key]) for key in ['layout','reference']]
        sections = ['new JournalSection('+','.join(quoted(s[k]) for k in ['kind','title','prompt'])+')' for s in t['sections']]
        native_templates.append('            new JournalTemplate('+','.join(args)+',\n                '+',\n                '.join(sections)+'),\n')
    native_templates += ['        };\n    }\n}\n']
    swift = [HEADER, 'import SwiftUI\n\nenum DesktopContract {\n    static let sourceDigest='+quoted(digest)+'\n']
    swift += ['    static let '+key[0].lower()+key[1:]+'='+str(value)+'\n' for key,value in numbers.items()]
    swift += ['    static let '+key[0].lower()+key[1:]+'=['+','.join(map(quoted,values))+']\n' for key,values in arrays.items() if key != 'Backgrounds']
    swift += ['}\n\nenum DesktopPalette {\n']
    def swift_color(hex_value):
        rgb = [int(hex_value[i:i+2],16) for i in [1,3,5]]
        return 'Color(red: '+str(rgb[0])+'.0/255, green: '+str(rgb[1])+'.0/255, blue: '+str(rgb[2])+'.0/255)'
    swift += ['    static let '+key[0].lower()+key[1:]+'='+swift_color(value)+'\n' for key,value in colors.items()]
    swift += ['    static let backgrounds=['+','.join(map(swift_color,c['design']['Backgrounds']))+']\n}\n\nenum DesktopFixtures {\n    static let layouts: [[Int]]=[\n']
    swift += ['        ['+','.join(map(str,[int(case['resize']),*case['original'],*case['delta'],*case['expected']]))+'],\n' for case in cases]
    swift += ['    ]\n}\n']
    return {
        'windows/Core/Shared/CollectionPolicy.g.cs':''.join(collection_cs),
        'app/src/main/java/com/myday/diary/diary/SharedCollection.g.kt':''.join(collection_kt),
        'app/src/main/java/com/myday/diary/diary/SharedGrowth.g.kt': HEADER+'package com.myday.diary.diary\n\ninternal object SharedGrowth {\n'+''.join('    const val '+k+'='+str(v)+'\n' for k,v in c['growth'].items())+'    val profiles=arrayOf(\n'+''.join('        intArrayOf('+','.join(map(str,[p['expectedDays'],*p['week']]))+'),\n' for p in c['growthProfiles'])+'    )\n}\n',
        'windows/Core/Shared/DesktopContract.g.cs': ''.join(cs),
        'windows/Core/Shared/Templates.g.cs': ''.join(native_templates),
        'macos/Sources/MyDay/SharedDesktop.g.swift': ''.join(swift),
        'macos/Sources/MyDay/Resources/templates.json': json.dumps(templates,ensure_ascii=False,indent=2)+'\n',
        'server/cloudflare/src/shared-chat.g.ts': HEADER+'export const DesktopChat = '+json.dumps(c['chat'],indent=2)+' as const;\n',
        'server/chat_contract_generated.py': '# Generated by tools/sync-desktop.py from shared/desktop.json.\n'+''.join(key+' = '+str(value)+'\n' for key,value in c['chat'].items()),
    }

def sync(root=ROOT, check=False):
    stale = []
    for name, text in render(root).items():
        path = root/name
        if not path.exists() or path.read_text(encoding='utf-8') != text:
            stale.append(name)
            if not check:
                path.parent.mkdir(parents=True,exist_ok=True)
                path.write_text(text,encoding='utf-8',newline='\n')
    if check and stale: raise ValueError('Run python tools/sync-desktop.py; stale generated files: '+', '.join(stale))
    return stale

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    changed=sync(check=args.check)
    print('Shared desktop sources verified.' if args.check else 'Shared desktop generated: '+str(len(changed))+' file(s).')

if __name__ == '__main__':
    main()
