"""Bundle the same dependency-free handoff page in each native application."""
import argparse,json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def sync(check=False):
    source=(ROOT/'shared/device-link.html').read_text(encoding='utf-8')
    outputs={'windows/Core/Shared/DeviceLinkPage.g.cs':'// Generated by tools/sync-device-link.py\nnamespace MyDay.Windows.Core { public static class DeviceLinkPage {public const string Html='+json.dumps(source,ensure_ascii=False)+';} }\n',
        'app/src/main/assets/device-link.html':source,'macos/Sources/MyDay/Resources/device-link.html':source}
    for name,text in outputs.items():
        path=ROOT/name
        if check:
            if not path.exists() or path.read_text(encoding='utf-8')!=text:raise ValueError('Run python tools/sync-device-link.py: '+name)
        else:path.write_text(text,encoding='utf-8',newline='\n')
if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');sync(p.parse_args().check)
