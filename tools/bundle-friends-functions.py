"""Produce single-file Dashboard deployment sources from the tested modules."""
from pathlib import Path
import re
import sys

root=Path(__file__).resolve().parents[1]
destination=Path(sys.argv[1])
destination.mkdir(parents=True,exist_ok=True)
functions=root/'supabase/functions'
for name,helpers in [('myday-kakao-login',['body.mjs','kakao-auth.mjs']),('myday-kakao-events',['body.mjs'])]:
    parts=['// @ts-nocheck\n// Generated by tools/bundle-friends-functions.py; edit the source modules.\n']
    for helper in helpers:
        text=(functions/'_shared'/helper).read_text(encoding='utf-8')
        parts.append(re.sub(r'(?m)^export ','',text))
    entry=(functions/name/'index.ts').read_text(encoding='utf-8')
    parts.append(re.sub(r"(?m)^import .*from '\.\./_shared/[^']+';\n",'',entry))
    (destination/(name+'.ts')).write_text('\n'.join(parts),encoding='utf-8')
print('Prepared 2 standalone Edge Function sources.')
