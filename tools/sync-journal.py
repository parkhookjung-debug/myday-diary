"""Generate the small offline journal policy for all three native apps."""
import argparse
import json
import re
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
def render(root=ROOT):
    p=json.loads((root/'shared/journal-tools.json').read_text(encoding='utf-8'))
    if p.get('version')!=1 or not re.fullmatch(r'\d+\.\d+\.\d+',p.get('appVersion','')): raise ValueError('Unsupported journal policy version')
    for k in ('historyLimitBytes','historyLimitFiles','historyIntervalSeconds','transferLifetimeSeconds','automaticBackupCount','automaticBackupLimitBytes'):
        if type(p.get(k)) is not int or not 1<=p[k]<=2_000_000_000: raise ValueError('Invalid positive policy limit: '+k)
    if set(p['reactions'])!={'record','habit','welcome'} or any(not isinstance(s,str) or not 1<=len(s)<=200 for s in p['reactions'].values()): raise ValueError('Invalid reaction messages')
    values={k:v for k,v in p.items() if k not in ('version','reactions')}
    values.update({k+'Reaction':v for k,v in p['reactions'].items()})
    quote=lambda v:json.dumps(v,ensure_ascii=False)
    cs='// Generated by tools/sync-journal.py.\nnamespace MyDay.Windows.Core { public static class JournalPolicy {\n'
    kt='// Generated by tools/sync-journal.py.\npackage com.myday.diary.data\nobject JournalPolicy {\n'
    sw='// Generated by tools/sync-journal.py.\nenum JournalPolicy {\n'
    for k,v in values.items():
        cs+='    public const '+('string' if isinstance(v,str) else 'int')+' '+k[0].upper()+k[1:]+'='+quote(v)+';\n'
        kt+='    const val '+k+'='+quote(v).replace('$','\\$')+'\n'
        sw+='    static let '+k+'='+quote(v)+'\n'
    return {'windows/Core/Shared/JournalPolicy.g.cs':cs+'}}\n',
            'windows/AssemblyInfo.g.cs':'// Generated by tools/sync-journal.py.\nusing System.Reflection;\n[assembly: AssemblyVersion("'+p['appVersion']+'.0")]\n[assembly: AssemblyFileVersion("'+p['appVersion']+'.0")]\n[assembly: AssemblyProduct("MyDay")]\n',
            'app/src/main/java/com/myday/diary/data/JournalPolicy.g.kt':kt+'}\n',
            'macos/Sources/MyDay/JournalPolicy.g.swift':sw+'}\n'}
def sync(check=False):
    for path,text in render().items():
        target=ROOT/path
        if check:
            if not target.exists() or target.read_text(encoding='utf-8')!=text: raise ValueError('Run python tools/sync-journal.py: '+path)
        else: target.write_text(text,encoding='utf-8',newline='\n')
if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');sync(parser.parse_args().check)
