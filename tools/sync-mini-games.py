"""Generate native game constants from common tuning. No user files."""
import argparse,json,math
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def sync(check=False):
 p=json.loads((ROOT/'shared/mini-games.json').read_text(encoding='utf-8'))
 assert p['format']=='myday-mini-games' and p['version']==1
 ranges={'JumpSeconds':(10,180),'JumpLives':(1,3),'JumpGravity':(1000,2400),'JumpLaunch':(600,850),'JumpSpeed':(180,380),'FetchSpeed':(180,600),'FetchRadius':(12,28),'FetchCatchRadius':(80,110),'SlingSeconds':(10,180),'SlingShots':(1,30),'SlingGravity':(100,1200),'SlingStrength':(3,12),'SlingMaxPull':(40,180),'FishSeconds':(10,180),'FishBiteWindow':(.5,3),'FishWaitMin':(.5,3),'FishWaitMax':(1,8),'FishZoneWidth':(.1,.5)}
 assert set(p)==set(ranges)|{'format','version'}
 for key,(a,b) in ranges.items():assert isinstance(p[key],(int,float)) and not isinstance(p[key],bool) and math.isfinite(p[key]) and a<=p[key]<=b,key
 assert isinstance(p['JumpLives'],int) and isinstance(p['SlingShots'],int) and p['FishWaitMin']<p['FishWaitMax']
 text='// Generated by tools/sync-mini-games.py.\nnamespace MyDay.Windows.Core { public static class MiniGameRules {\n'
 for key in ranges:text+='public const '+('int' if key in ('SlingShots','JumpLives') else 'double')+' '+key+'='+str(p[key])+';\n'
 text+='}}\n';path=ROOT/'windows/Core/Shared/MiniGameRules.g.cs'
 if check:assert path.read_text(encoding='utf-8')==text,'Run tools/sync-mini-games.py'
 else:path.write_text(text,encoding='utf-8',newline='\n')
if __name__=='__main__':
 parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');sync(parser.parse_args().check)
