"""Generate Windows mini-game tuning from the shared rules, without user data."""
import argparse,json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def sync(check=False):
    p=json.loads((ROOT/'shared/snack-game.json').read_text(encoding='utf-8'))
    assert p['format']=='myday-snack-game' and p['version']==1
    assert 10<=p['roundSeconds']<=180 and 1<=p['startingLives']<=3
    assert 1<=p['foodPoints']<=100 and 100<=p['playerSpeed']<=2000
    assert .2<=p['invulnerableSeconds']<=3 and 0<p['hazardProbability']<.7
    names={'roundSeconds':'RoundSeconds','startingLives':'StartingLives','foodPoints':'FoodPoints','playerSpeed':'PlayerSpeed','invulnerableSeconds':'InvulnerableSeconds','hazardProbability':'HazardProbability'}
    text='// Generated by tools/sync-snack-game.py.\nnamespace MyDay.Windows.Core { public static class SnackRules {\n'
    for key,name in names.items():
        kind='int' if key in ('startingLives','foodPoints') else 'double'
        text+='    public const '+kind+' '+name+'='+str(p[key])+';\n'
    text+='}}\n'
    path=ROOT/'windows/Core/Shared/SnackRules.g.cs'
    if check: assert path.read_text(encoding='utf-8')==text,'Run tools/sync-snack-game.py'
    else:path.write_text(text,encoding='utf-8',newline='\n')
if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');sync(parser.parse_args().check)
