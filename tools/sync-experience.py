"""Generate the offline onboarding/help copy; no network, no user records."""
import argparse,json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def render(root=ROOT):
    p=json.loads((root/'shared/experience.json').read_text(encoding='utf-8'))
    assert p['version']==1 and [s['id'] for s in p['sections']]==['start','map','rewards','update']
    assert all(isinstance(s[k],str) and 0<len(s[k])<4000 for s in p['sections'] for k in ('title','body'))
    economy=json.loads((root/'shared/collection.json').read_text(encoding='utf-8'))
    assert len(economy['weights'])==len(economy['names'])==4 and sum(economy['weights'])==10000
    odds=' / '.join(name+' '+format(weight/100,'g')+'%' for name,weight in zip(economy['names'],economy['weights']))
    assert '{odds}' in p['sections'][2]['body'], 'Keep the shared policy odds placeholder'
    p['sections'][2]['body']=p['sections'][2]['body'].replace('{odds}',odds)
    growth=json.loads((root/'shared/desktop.json').read_text(encoding='utf-8'))['growth']
    assert growth=={'GrowthMaxLevel':100,'GrowthMaxXP':3590,'GrowthAttendanceWeekXP':10,'GrowthDailyActivityXP':40}, 'Update growth help when changing the growth model'
    q=lambda s:json.dumps(s,ensure_ascii=False)
    arrays={'Titles':[s['title'] for s in p['sections']], 'Bodies':[s['body'] for s in p['sections']]}
    cs='// Generated by tools/sync-experience.py.\nnamespace MyDay.Windows.Core { public static class ExperienceCatalog {\npublic const string Title='+q(p['title'])+';\n'
    kt='// Generated by tools/sync-experience.py.\npackage com.myday.diary.data\nobject ExperienceCatalog {\nconst val title='+q(p['title'])+'\n'
    sw='// Generated by tools/sync-experience.py.\nenum ExperienceCatalog {\nstatic let title='+q(p['title'])+'\n'
    for key,values in arrays.items():
        cs+='public static readonly string[] '+key+'={'+','.join(map(q,values))+'};\n'
        kt+='val '+key.lower()+'=listOf('+','.join(q(v).replace('$','\$') for v in values)+')\n'
        sw+='static let '+key.lower()+'=['+','.join(map(q,values))+']\n'
    return {'windows/Core/Shared/ExperienceCatalog.g.cs':cs+'}}\n','app/src/main/java/com/myday/diary/data/ExperienceCatalog.g.kt':kt+'}\n','macos/Sources/MyDay/ExperienceCatalog.g.swift':sw+'}\n'}
def sync(check=False):
    for name,value in render().items():
        path=ROOT/name
        if check:assert path.read_text(encoding='utf-8')==value,'Run tools/sync-experience.py: '+name
        else:path.write_text(value,encoding='utf-8',newline='\n')
if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');sync(p.parse_args().check)
